// ยิงพร้อมกันทีละชุดเล็ก — เวลารวมเท่ากับสายที่ยาวที่สุด ไม่ใช่ผลรวม
// แต่ไม่ยิงทีเดียวทั้งหมด เพราะจะชน rate limit แล้วเสียคำขอทิ้งฟรีๆ
const CONCURRENCY = 3

const args = process.argv.slice(2)
const only = (args.find(a => a.startsWith('--only=')) || '').slice(7)
const dry = args.includes('--dry')

const missing = ['ANTHROPIC_API_KEY', 'VITE_SUPABASE_URL', 'VITE_SUPABASE_ANON_KEY']
  .filter(k => !process.env[k])
if(missing.length && !dry){
  console.error('ขาด env: ' + missing.join(', ') + '\nรันแบบ: node --env-file=.env scripts/seed-ref-answers.mjs')
  process.exit(1)
}

const list = only ? SEEDS.filter(s => s.tag.includes(only) || s.law_name.includes(only)) : SEEDS
if(!list.length){ console.error('ไม่มีคำถามที่ตรงกับ --only=' + only); process.exit(1) }

if(dry){
  list.forEach(s => console.log(`[${s.tag}] ${s.anchor_question}`))
  process.exit(0)
}

const LABEL = {
  answered: '✓ ตอบได้',
  not_answered: '× ยังไม่ได้คำตอบ',
}

let ok = 0, fail = 0, cached = 0
const started = Date.now()

for(let i = 0; i < list.length; i += CONCURRENCY){
  const batch = list.slice(i, i + CONCURRENCY)
  const results = await Promise.all(batch.map(async seed => {
    const t0 = Date.now()
    // deadline เผื่อไว้ยาวกว่าฝั่ง serverless เพราะสคริปต์นี้ไม่ได้ถูก maxDuration บังคับ
    const res = await answerAnchoredQuestion({ ...seed, ref_type: 'whole_law' }, Date.now() + 240_000)
    return { seed, res, ms: Date.now() - t0 }
  }))
  for(const { seed, res, ms } of results){
    if(res.status === 'answered') ok++; else fail++
    if(res.from_cache) cached++
    console.log(`${LABEL[res.status] || res.status}  [${seed.tag}]  ${(ms / 1000).toFixed(1)}s`
      + (res.from_cache ? '  (มีใน cache อยู่แล้ว)' : ''))
    if(res.status === 'answered'){
      console.log(`   ${res.law_name}${res.section_ref ? ' · ' + res.section_ref : ''}`)
      console.log(`   ${String(res.answer_plain).slice(0, 160)}`)
      if(res.from_secondary_source) console.log('   ⚠ อ่านจากฉบับรวมขององค์กรวิชาชีพ — ติดป้ายให้ผู้ใช้ตรวจกับต้นฉบับแล้ว')
      if(res.unverified_numbers?.length) console.log('   ⚠ ตรวจตัวเลข ' + res.unverified_numbers.join(', '))
    } else {
      console.log(`   ${res.note || '(ไม่มีเหตุผลกำกับ)'}`)
    }
  }
}

console.log(`\nเสร็จใน ${((Date.now() - started) / 1000).toFixed(1)}s · ตอบได้ ${ok} · ยังไม่ได้คำตอบ ${fail}`
  + (cached ? ` · ใช้ของเดิมจาก cache ${cached}` : ''))
console.log('คำตอบถูกเขียนลง lg_ref_answers แล้ว (อายุ 180 วัน) — การสรุปครั้งถัดไปที่ถามคำถามเดียวกันจะไม่เสียคำขอ')
