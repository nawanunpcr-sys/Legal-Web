// ซึ่ง จป. ทำต่อเองได้ใน 2 นาที แทนที่จะต้องเริ่มค้นใหม่ตั้งแต่ต้น

import { askClaude, WEB_SEARCH_TOOL } from './law-source.js'

const LEAD_SYSTEM = `คุณกำลังช่วย "ระบุตัวฉบับกฎหมาย" ไม่ใช่ตอบคำถามกฎหมาย

ผู้ใช้มีคำถามหนึ่ง และระบบค้นในเว็บราชการที่เชื่อถือได้แล้วไม่เจอตัวบท
งานของคุณคือค้นเว็บแบบกว้าง (รวมบล็อก บทความ สรุปของที่ปรึกษา เว็บข่าว)
เพื่อหาว่า **เกณฑ์ที่ผู้ใช้ถามถึงถูกกำหนดไว้ในกฎหมายฉบับไหน ข้อไหน**

⚠ สิ่งที่คุณกำลังทำคือ "ชี้ที่อยู่" ไม่ใช่ "ตอบคำถาม"
ระบบจะไม่ใช้ข้อความที่คุณอ่านเจอเป็นคำตอบเด็ดขาด แต่จะเอาชื่อฉบับที่คุณระบุ
ไปเปิดตัวบทจริงจากราชกิจจานุเบกษาหรือเว็บหน่วยงานเอง
ดังนั้น **ความถูกต้องของ "ชื่อฉบับ + ปี + เลขข้อ" สำคัญกว่าทุกอย่าง**

หลักการ:
1. ห้ามเดาชื่อฉบับ · ไม่มีแหล่งไหนระบุชัด ให้ตอบ found:false
2. ระบุให้ครบที่สุดเท่าที่แหล่งบอก: ชื่อเต็ม · ฉบับที่ · พ.ศ. · เลขข้อ/มาตรา
   ถ้ามีเลขราชกิจจานุเบกษา (เล่ม/ตอน/หน้า) ให้ใส่ด้วย เพราะเปิดตรงได้เลย
3. ถ้าหลายแหล่งบอกไม่ตรงกัน ให้เลือกที่ "หลายแหล่งตรงกันมากที่สุด" แล้วบอกใน note ว่าขัดกัน
4. ระวังฉบับก่อนแก้ไข — บล็อกไทยมักคัดของเก่ามาโดยไม่บอก
   เจอสัญญาณว่ามีฉบับแก้ไขใหม่กว่า ให้ระบุฉบับใหม่ที่สุดที่พบ และเขียนไว้ใน note
5. ใส่เกณฑ์ที่แหล่งนั้นบอกไว้ลง criteria_seen ได้ แต่ต้องเข้าใจว่ามันจะถูกติดป้ายว่า
   "ยังไม่ยืนยันกับตัวบท" และ **จะไม่ถูกบันทึกเข้าทะเบียนกฎหมาย** ไม่ว่ากรณีใด
   มันมีไว้ให้ผู้ใช้เห็นว่า "เขาว่ากันว่าเท่าไร" เพื่อจะได้รู้ว่าต้องไปตรวจอะไร
   คัดมาตามที่แหล่งเขียนจริง ห้ามเรียบเรียงจนความหมายเปลี่ยน ห้ามเติมจากความจำ

ตอบเป็น JSON เท่านั้น ห้ามมี markdown fence:
{"found":true|false,
 "law_name":"ชื่อเต็มของกฎหมายที่กำหนดเกณฑ์นี้ พร้อมปี พ.ศ.",
 "issue_no":"ฉบับที่ N ถ้ามี มิฉะนั้นค่าว่าง",
 "section_ref":"ข้อ/มาตราที่กำหนดเกณฑ์นี้ ถ้าระบุได้",
 "gazette_ref":"เล่ม N ตอนที่ M หน้า P ถ้าแหล่งระบุ มิฉะนั้นค่าว่าง",
 "criteria_seen":"เกณฑ์ที่แหล่งนั้นระบุ สั้น ๆ ไม่เกิน 200 ตัวอักษร — ยังไม่ยืนยัน",
 "seen_on":"ชื่อเว็บ/แหล่งที่บอกข้อมูลนี้ (ไว้ให้ผู้ใช้ประเมินเอง)",
 "agreement":"หลายแหล่งตรงกัน"|"แหล่งเดียว"|"แหล่งขัดกัน",
 "note":"ข้อสังเกต เช่น พบว่ามีฉบับแก้ไขใหม่กว่า"}`

/**
 * ค้นเว็บกว้างเพื่อระบุตัวฉบับ · คืน null เมื่อระบุไม่ได้
 * criteria_seen ที่คืนมาเป็น "สิ่งที่แหล่งนอกบอก" ไว้แสดงให้ผู้ใช้เห็นเท่านั้น
 * ระบบไม่เอาไปเป็น answer_plain / source_excerpt และไม่เขียนลงทะเบียน
 */
export async function findLawIdentity(question, lawHint = '', ctx = ''){
  const q = String(question || '').trim()
  if(!q) return null
  const out = await askClaude({
    system: [{ type: 'text', text: LEAD_SYSTEM, cache_control: { type: 'ephemeral' } }],
    content: [
      `คำถามที่ผู้ใช้ต้องการคำตอบ: ${q}`,
      lawHint ? `ตัวบทฉบับหลักบอกให้ไปดู: ${lawHint}` : '',
      ctx || '',
      '',
      'ค้นเว็บให้กว้าง แล้วบอกมาว่า "เกณฑ์นี้อยู่ในกฎหมายฉบับไหน ข้อไหน"',
      'สิ่งที่สำคัญที่สุดคือชื่อฉบับกับเลขข้อ — ระบบจะไปเปิดตัวบทจริงจากชื่อที่คุณให้มา',
    ].filter(Boolean).join('\n'),
    tools: [WEB_SEARCH_TOOL],
  })
  if(!out || out.found !== true) return null
  const name = String(out.law_name || '').trim()
  if(name.length < 10) return null            // ชื่อสั้นเกินกว่าจะเอาไปเปิดฉบับได้จริง
  return {
    law_name: name,
    issue_no: String(out.issue_no || '').trim(),
    section_ref: String(out.section_ref || '').trim(),
    gazette_ref: String(out.gazette_ref || '').trim(),
    criteria_seen: String(out.criteria_seen || '').trim().slice(0, 200),
    seen_on: String(out.seen_on || '').trim(),
    agreement: String(out.agreement || '').trim(),
    note: String(out.note || '').trim(),
  }
}

// ข้อความบอกผู้ใช้เมื่อได้เบาะแสแต่เปิดตัวบทจริงไม่สำเร็จ
// ต้องอ่านแล้วรู้ทันทีว่า "นี่ยังไม่ใช่คำตอบ" และ "ต้องไปทำอะไรต่อ"
// เขียนให้ชัดว่ามาจากเว็บนอกรายการ เพื่อให้ผู้ใช้ประเมินน้ำหนักเองได้
export function leadNote(lead){
  if(!lead) return ''
  const where = [lead.law_name, lead.issue_no, lead.section_ref].filter(Boolean).join(' · ')
  const conflict = lead.agreement === 'แหล่งขัดกัน' ? ' · ⚠ แหล่งที่ค้นเจอบอกไม่ตรงกัน' : ''
  const single = lead.agreement === 'แหล่งเดียว' ? ' · พบจากแหล่งเดียว ยังไม่ได้ยืนยันซ้ำ' : ''
  // เกณฑ์ที่แหล่งนอกบอกไว้ แสดงได้ แต่ต้องอ่านแล้วรู้ทันทีว่ายังไม่ยืนยัน
  //
  // ผู้ใช้ถามว่า "ถ้ามันถูกต้องก็ใช้เป็นคำตอบได้ไม่ใช่หรือ" — ใช่ในทางเนื้อหา
  // แต่ "ถ้ามันถูกต้อง" คือสิ่งที่พิสูจน์ไม่ได้ตอนผู้ตรวจ ISO ถามว่าอ้างจากอะไร
  // จึงแสดงให้เห็นว่า "เขาว่ากันว่าเท่าไร" เพื่อให้ จป. รู้ว่าต้องไปตรวจอะไร
  // แต่สถานะยังเป็น not_answered ซึ่งทำให้ mergeAnswerText() ไม่เอาไปเขียนลงทะเบียน
  // (กติกาเดิมของระบบ: รวมเฉพาะ status === 'answered' เท่านั้น)
  const seen = lead.criteria_seen
    ? `· เขาว่ากันว่า: "${lead.criteria_seen}" — ยังไม่ยืนยันกับตัวบท ห้ามใช้อ้างอิงจนกว่าจะเปิดฉบับจริง`
    : ''
  return [
    `ยังเปิดตัวบทจริงไม่ได้ แต่ค้นจากเว็บทั่วไปแล้วชี้ว่าเกณฑ์นี้อยู่ใน ${where}`,
    lead.gazette_ref ? `(ราชกิจจาฯ ${lead.gazette_ref})` : '',
    `— ข้อมูลนี้มาจาก${lead.seen_on ? lead.seen_on : 'เว็บนอกรายการที่เชื่อถือได้'} ยังไม่ผ่านการเปิดตัวบทยืนยัน`,
    'ต้องเปิดฉบับนี้ตรวจเองก่อนใช้อ้างอิง',
    conflict, single, seen,
    lead.note ? `· ${lead.note}` : '',
  ].filter(Boolean).join(' ')
}
