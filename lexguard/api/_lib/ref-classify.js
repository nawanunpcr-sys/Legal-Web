// P17 · จำแนก "การอ้างถึง" เป็น 3 ชนิด ก่อนตัดสินใจว่าจะไปทำอะไรกับมัน
//
// ปัญหาที่แก้: ระบบเดิมปฏิบัติกับทุกการอ้างถึงเหมือนกันหมด คือ "ไปดึงกฎหมายฉบับนั้นมา"
// แต่การอ้างถึง 3 แบบนี้ต้องการคนละอย่างสิ้นเชิง:
//
//   specific   "ตามความในมาตรา 31"                  → ดึงมาตรานั้น (ทำได้อยู่แล้ว)
//   whole_law  "ตามกฎหมายว่าด้วยการควบคุมอาคาร"      → ห้ามดึงทั้งฉบับ ต้องแปลงเป็นคำถามก่อน
//   pending    "ตามที่รัฐมนตรีประกาศกำหนด"           → ห้ามค้น ตัวบทยังไม่ถูกออกมา
//
// pending สำคัญที่สุด — ในกฎกระทรวงควบคุมสถานประกอบกิจการฯ 2560 มีถึง 7 จุดจาก 20 ข้อ
// ระบบเดิมไปค้นแล้วไม่เจอ จึงคืน not_found เหมือนกรณีค้นพลาด
// ทั้งที่ความจริงคือ "ตัวบทยังไม่ออก" ซึ่งเป็นคนละเรื่อง และไม่ควรถูกประเมินว่าไม่สอดคล้อง
//
// หลักการเดียวกับด่านอื่นของระบบ: ตัดสินจากหลักฐาน (ข้อความที่คัดมาจากตัวบทจริง)
// ไม่ใช่จากป้ายที่โมเดลติดมาเอง · ป้ายของโมเดลเก็บไว้เทียบใน note เฉยๆ

// หน่วยงานที่มีอำนาจออกกฎหมายลำดับรอง — ถ้าตัวบทชี้ไปที่ "คน" กลุ่มนี้ว่าจะกำหนดทีหลัง
// แปลว่ายังไม่มีตัวบทให้ค้น ต่างจากการชี้ไปที่ "กฎหมายฉบับหนึ่ง" ที่ออกแล้ว
const AUTHORITY = 'รัฐมนตรี|อธิบดี|ปลัดกระทรวง|เลขาธิการ|คณะกรรมการ|ผู้ว่าราชการจังหวัด|เจ้าพนักงานท้องถิ่น|ราชการส่วนท้องถิ่น|นายทะเบียน|ผู้อำนวยการ|อธิการบดี'

// "รัฐมนตรีประกาศกำหนด" · "ที่อธิบดีกำหนด" · "คณะกรรมการประกาศกำหนด"
// ระยะ 0-25 ตัวอักษรกันคำคั่นอย่าง "ว่าการกระทรวงสาธารณสุข" แต่ไม่กว้างจนจับข้ามประโยค
const PENDING_RE = new RegExp(`(?:${AUTHORITY})[\\s\\S]{0,25}?(?:ประกาศกำหนด|ประกาศ|กำหนด)`)

// ตัวบทที่ "ออกมาแล้ว" — มีตัวระบุฉบับที่เปิดหาได้จริง
// ต้องเช็คก่อน PENDING_RE เสมอ ไม่งั้น "ประกาศกระทรวงสาธารณสุข เรื่อง X พ.ศ. 2561"
// จะถูกตีเป็น pending ทั้งที่เป็นฉบับที่ออกแล้วและมีตัวบทให้ค้น
const CONCRETE_RE = /พ\s*\.?\s*ศ\s*\.?\s*[๐-๙\d]{4}|^กฎหมายว่าด้วย|เรื่อง\s*\S|ฉบับที่\s*[๐-๙\d]|ประมวล/

// มาตรา/ข้อ ที่ระบุเลขเจาะจง — ตัวชี้ว่าเป็น specific
const CLAUSE_RE = /(?:มาตรา|ข้อ|ภาค|หมวด|ส่วนที่)\s*[๐-๙\d]/

// ตัวบทบอกให้ทำอย่างไร "ระหว่างรอ" ประกาศฉบับจริง
// (ข้อ 23 ของกฎกระทรวงตัวอย่าง: ให้ใช้หลักเกณฑ์ตามกฎหมายอื่นที่เกี่ยวข้องไปพลางก่อน)
const INTERIM_RE = /ไปพลางก่อน|ในระหว่างที่ยังไม่มี|จนกว่าจะมี(?:การ)?ประกาศ|เท่าที่ไม่ขัด/

function has(re, s){ return re.test(String(s || '')) }

// ดึงชื่อผู้มีอำนาจออกประกาศ จากข้อความที่คัดมาจากตัวบทจริง
// คืนค่าว่างเมื่อหาไม่เจอ — ห้ามเดา เพราะ UI เอาไปแสดงว่า "รออะไรจากใคร"
export function issuingAuthority(quote){
  const m = String(quote || '').match(new RegExp(`(?:${AUTHORITY})(?:ว่าการกระทรวง\\S{0,20}|กรม\\S{0,20})?`))
  return m ? m[0].trim() : ''
}

// จำแนกการอ้างถึง 1 รายการ · คืนเฉพาะฟิลด์ที่โค้ดตัดสินได้เอง
// หลักฐานที่ใช้: appears_in (ข้อความคำต่อคำจากตัวบท ผ่านด่าน verifyRelatedRefs มาแล้ว)
export function classifyRef(ref){
  const quote = String(ref?.appears_in || '').trim()
  const name = String(ref?.law_name || '').trim()
  const clause = String(ref?.clause || '').trim()

  // (1) อ้างมาตรา/ข้อเจาะจง → ดึงมาตรานั้นตรงๆ ได้เลย โฟลว์เดิมทำได้ดีอยู่แล้ว
  //     เช็คก่อนทุกอย่าง เพราะการมีเลขมาตราคือหลักฐานที่หนักแน่นที่สุดว่ามีตัวบทให้เปิด
  if(clause && clause !== 'ทั้งฉบับ' && has(CLAUSE_RE, clause)){
    return { ref_type: 'specific', issuing_authority: '', interim_rule: '' }
  }

  // (2) ตัวบทที่ถูกอ้างยังไม่ออก → ห้ามค้น
  //     ต้องไม่มีตัวระบุฉบับที่เปิดหาได้จริงทั้งในชื่อและในข้อความที่คัดมา
  const concrete = has(CONCRETE_RE, name) || has(CONCRETE_RE, quote)
  if(!concrete && has(PENDING_RE, quote)){
    return {
      ref_type: 'pending',
      issuing_authority: issuingAuthority(quote),
      interim_rule: has(INTERIM_RE, quote) ? quote : '',
    }
  }

  // (3) ที่เหลือ = อ้างชื่อกฎหมายโดยไม่ระบุข้อ → ห้ามดึงทั้งฉบับ เข้าโฟลว์คำถาม
  return { ref_type: 'whole_law', issuing_authority: '', interim_rule: '' }
}

// จำแนกทั้งชุด · เก็บป้ายที่โมเดลติดมาไว้เทียบ (ai_ref_type) แต่ไม่ใช้ตัดสิน
export function classifyRefs(refs){
  return (Array.isArray(refs) ? refs : []).map(r => {
    const c = classifyRef(r)
    const aiInterim = String(r?.interim_rule || '').trim()
    return {
      ...r,
      ref_type: c.ref_type,
      ai_ref_type: String(r?.ref_type || '') || null,
      issuing_authority: c.issuing_authority || String(r?.issuing_authority || '').trim(),
      // วิธีปฏิบัติระหว่างรอประกาศ — ต้องมีข้อความจากตัวบทรองรับก่อนเสมอ (c.interim_rule)
      // มีหลักฐานแล้วจึงใช้สำนวนที่โมเดลเรียบเรียงมา ซึ่งอ่านง่ายกว่าข้อความดิบ
      // ไม่มีหลักฐาน = ทิ้ง แม้โมเดลจะแถมมา · ปล่อยผ่านเท่ากับให้โมเดลแต่งวิธีปฏิบัติเองได้
      // ซึ่งอันตรายกว่าไม่บอกอะไรเลย เพราะ จป. จะเอาไปทำตามจริง
      interim_rule: (c.ref_type === 'pending' && c.interim_rule) ? (aiInterim || c.interim_rule) : '',
    }
  })
}

// ── question_key · ทำให้คำถามที่ถามเรื่องเดียวกันชนกันใน cache ────────────────
// ภาษาไทยไม่เว้นวรรคระหว่างคำ การเว้นวรรคจึงเป็นเรื่องของคนพิมพ์ล้วนๆ ตัดทิ้งได้ทั้งหมด
const THAI_DIGITS = '๐๑๒๓๔๕๖๗๘๙'
export function normalizeQuestionKey(q){
  return String(q || '')
    .replace(/[๐-๙]/g, d => String(THAI_DIGITS.indexOf(d)))
    .replace(/[​­﻿]/g, '')          // zero-width / soft hyphen / BOM
    .replace(/[\s ]+/g, '')                    // ช่องว่างทุกชนิด
    .replace(/[?？!！.,·ๆฯ"'()\[\]{}—–\-]/g, '')     // เครื่องหมายวรรคตอนที่ไม่เปลี่ยนความหมาย
    .toLowerCase()
    .slice(0, 400)                                  // กัน key ยาวเกินจน index ไม่ไหว
}

// ── topic_key · คีย์รองที่ทนต่อการเปลี่ยนสำนวนคำถาม ──────────────────────────
// question_key ชนเฉพาะเมื่อคำถาม "ตัวอักษรตรงกัน" หลัง normalize ซึ่งแทบไม่เกิด
// เพราะคำถามถูกโมเดลเรียบเรียงใหม่ทุกรอบ · ผลคือจ่ายเงินค้นซ้ำเพื่อคำตอบเดิม
//
// คีย์รองผูกกับ (กฎหมายที่อ้างถึง + เรื่องที่ถาม) แทนตัวอักษรของคำถาม
// เรื่องมาจากตารางคำที่คุมเอง ไม่ใช่การตัดคำอัตโนมัติ — ภาษาไทยไม่เว้นวรรค
// การเดาขอบเขตคำผิดแล้วจับคู่ผิด = หยิบคำตอบของกฎหมายคนละเรื่องมาแสดง
//
// กติกากันหยิบผิด: เข้าเรื่องเดียวเท่านั้นจึงใช้ได้ · เข้า 0 หรือ 2 เรื่องขึ้นไป = ไม่ออกคีย์
// (คำถามที่คร่อม 2 เรื่อง เช่น "แสงสว่างในห้องน้ำ" ต้องค้นใหม่ ไม่ใช่เดาว่าเป็นเรื่องไหน)
const TOPICS = [
  ['toilet',      /ห้องน้ำ|ห้องส้วม|ถ่ายอุจจาระ|ถ่ายปัสสาวะ|อ่างล้างมือ|สุขภัณฑ์/],
  ['light',       /แสงสว่าง|ความเข้มของแสง|ลักซ์|lux/i],
  ['ventilation', /ระบายอากาศ|ปรับภาวะอากาศ|เปลี่ยนถ่ายอากาศ/],
  ['fireexit',    /ทางหนีไฟ|บันไดหนีไฟ|ทางออกฉุกเฉิน|ป้ายบอกทาง/],
  ['fireext',     /เครื่องดับเพลิง|สัญญาณเตือนเพลิงไหม้|ระบบดับเพลิง/],
  ['healthcheck', /ตรวจสุขภาพ|สมุดสุขภาพ|ปัจจัยเสี่ยง/],
  ['drinkwater',  /น้ำดื่ม|น้ำบริโภค|คุณภาพน้ำประปา/],
  ['wastewater',  /น้ำทิ้ง|น้ำเสีย|มาตรฐานการระบายน้ำ/],
  ['greasetrap',  /บ่อดักไขมัน|กากไขมัน/],
  ['pest',        /แมลง|สัตว์ที่เป็นพาหะ|พาหะนำโรค/],
  ['noise',       /เสียงรบกวน|มลพิษทางเสียง|ระดับเสียง|เดซิเบล/],
  ['chemical',    /สารเคมีอันตราย|ล้างตา|ฝักบัวชำระล้าง|วัตถุอันตราย/],
  ['waste',       /มูลฝอย|ขยะ|ของเสียอันตราย/],
  ['food',        /สุขาภิบาลอาหาร|โรงอาหาร|ห้องครัว|ผู้สัมผัสอาหาร/],
  ['distance',    /ระยะห่าง|สถานที่ตั้ง|ห่างจากศาสนสถาน/],
]

export function normalizeTopicKey(lawName, question){
  const law = normalizeQuestionKey(lawName).slice(0, 120)
  if(law.length < 8) return ''            // ชื่อกฎหมายสั้นเกินกว่าจะระบุฉบับได้ชัด
  const q = String(question || '')
  const hit = TOPICS.filter(([, re]) => re.test(q))
  if(hit.length !== 1) return ''
  return `${law}|${hit[0][0]}`
}

// ── เกณฑ์ "คำถามที่ใช้ได้" ────────────────────────────────────────────────────
// คำถามกว้างๆ อย่าง "กฎหมายควบคุมอาคารกำหนดอะไรบ้าง" ค้นแล้วได้กฎหมายทั้งฉบับกลับมา
// ซึ่งคือปัญหาเดิมที่ P17 ตั้งใจแก้ · ปล่อยคำถามแบบนี้ผ่านไปเท่ากับไม่ได้แก้อะไร
const VAGUE_RE = /กำหนดอะไรบ้าง|มีอะไรบ้าง|ว่าอย่างไร|เกี่ยวกับอะไร|คืออะไร$/
const MIN_Q = 25   // สั้นกว่านี้ใส่ครบ 3 อย่าง (เรื่อง + บริบท + สิ่งที่ต้องการ) ไม่ได้

export function questionUsable(q){
  const s = String(q || '').trim()
  if(s.length < MIN_Q) return false
  if(VAGUE_RE.test(s)) return false
  return true
}
